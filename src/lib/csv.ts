/**
 * Minimal CSV writer (RFC 4180 quoting) with protection against spreadsheet
 * formula injection: text cells starting with =, +, -, @, tab or carriage
 * return are prefixed with an apostrophe so Excel/Sheets treat them as text.
 */
export type CsvCell = string | number | null | undefined;

const FORMULA_START = /^[=+\-@\t\r]/;

export function csvCell(value: CsvCell): string {
  if (value === null || value === undefined) return '';
  let text = typeof value === 'number' ? String(value) : value;
  if (typeof value === 'string' && FORMULA_START.test(text)) text = `'${text}`;
  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

